"""Generate the paper's LaTeX tables from saved evaluation outputs.

Usage: python scripts/make_tables.py /path/to/data

Reads only existing evaluation tables under <data>/gaze_accuracy (nothing is
recomputed or written to the dataset) and writes figures/tab_driving_offsets.tex
and figures/tab_controlled_factors.tex. Standard library only.

Driving values come from offset/driving/category_summary.csv: calibrators are
averaged within a fold, then the five folds are averaged equally (the reporting
table named in the benchmark README). Controlled values come from
factors/controlled/{tests,levels}.csv; "significant" means Holm p < .05.
"""
import csv
import statistics
import sys
from pathlib import Path

DATA = Path(sys.argv[1] if len(sys.argv) > 1 else "/home/william/data") / "gaze_accuracy"
OUT = Path(__file__).resolve().parents[1] / "figures"
DRIVING = DATA / "offset/driving/category_summary.csv"
FACTORS = DATA / "factors/controlled"
PARTICIPANTS = {"william": "P1", "katharina": "P2"}
ALPHA = 0.05


def rows(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def driving_table():
    summary = {(r["participant"], r["category"]): float(r["median_error_deg"]) for r in rows(DRIVING)}
    sources = ["Raw driving", "Chessboard E4 · full 15", "Chessboard E5 · pooled", "Driving · pooled 20%"]
    budget = {"random": ["Driving · single scene"] + [f"Driving random · {k}" for k in (2, 3, 4, 5, 8)],
              "layout": [None, "Driving line · 2", "Driving triangle · 3", "Driving rectangle · 4",
                         "Driving rectangle + center · 5", None]}

    def cell(key, category, bold=False):
        if category is None:
            return "--"
        value = f"{summary[(key, category)]:.2f}"
        return f"\\textbf{{{value}}}" if bold else value

    lines = [
        r"% Generated by scripts/make_tables.py from gaze_accuracy/offset/driving/category_summary.csv.",
        r"\begin{tabular}{@{}l@{\hskip 4pt}c@{\hskip 6pt}cc@{\hskip 6pt}c@{}}",
        r"\toprule",
        r" & \multicolumn{1}{c}{Uncorrected} & \multicolumn{2}{c}{Laboratory offset} & In-situ offset \\",
        r"\cmidrule(lr){2-2}\cmidrule(lr){3-4}\cmidrule(l){5-5}",
        r" & raw gaze & 1 board & all boards & 20\% of scenes \\",
        r"\midrule",
    ]
    for key, p in PARTICIPANTS.items():
        lines.append(f"{p} & " + " & ".join(cell(key, c, bold=(i == 3)) for i, c in enumerate(sources)) + r" \\")
    lines += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\\[4pt]",
        r"\begin{tabular}{@{}ll@{\hskip 6pt}cccccc@{}}",
        r"\toprule",
        r" & & \multicolumn{6}{c}{In-situ reference scenes $k$} \\",
        r"\cmidrule(l){3-8}",
        r" & selection & 1 & 2 & 3 & 4 & 5 & 8 \\",
        r"\midrule",
    ]
    for key, p in PARTICIPANTS.items():
        lines.append(f"\\multirow{{2}}{{*}}{{{p}}} & random & "
                     + " & ".join(cell(key, c) for c in budget["random"]) + r" \\")
        lines.append(r" & layout & " + " & ".join(cell(key, c) for c in budget["layout"]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (OUT / "tab_driving_offsets.tex").write_text("\n".join(lines) + "\n")


def test(participant, rq, comparison, metric, n_units=None):
    hits = [r for r in rows(FACTORS / "tests.csv")
            if r["participant"] == participant and r["rq"] == rq and r["comparison"].startswith(comparison)
            and r["metric"] == metric and (n_units is None or r["n_units"] == str(n_units))]
    return hits[-1]


def level(folder, view, participant, **match):
    for r in rows(FACTORS / folder / "levels.csv"):
        if r["view"] == view and r["participant"] == participant and all(r.get(k) == v for k, v in match.items()):
            return r
    raise KeyError((folder, view, participant, match))


def controlled_table():
    acc, s2s, pstd = "angular_error_median_deg", "p_rms_s2s_deg", "p_std_deg"
    d1 = float(test("William", "1_distance", "4 m − 1 m", acc)["mean_difference_deg"])
    k = lambda d: float(level("1_distance", "scope+experiment_distance_m", "Katharina Winter",
                               experiment_distance_m=d)["angular_error_median_deg_median"])
    d2 = k("4.0") - k("1.0")
    lower = {r["participant"]: r for r in rows(FACTORS / "tests.csv")
             if r["rq"] == "2_position" and r["comparison"] == "Lower − Upper" and r["metric"] == acc}
    lower_sig = sorted((float(r["mean_difference_deg"]), r["participant"]) for r in lower.values()
                       if float(r["p_holm"]) < ALPHA)
    rows_by_p = {}
    for r in rows(FACTORS / "2_position/levels.csv"):
        if r["view"] == "row":
            rows_by_p.setdefault(r["participant"], {})[r["row"]] = float(r["p_rms_s2s_deg_median"])
    assert all(v["Lower"] > v["Upper"] for v in rows_by_p.values()), "lower-row precision not consistent"
    pupils = []
    for name in {r["participant"] for r in rows(FACTORS / "4_illumination/levels.csv")}:
        b = float(level("4_illumination", "condition", name, condition="Bright")["pupil_mm_median"])
        d = float(level("4_illumination", "condition", name, condition="Dark")["pupil_mm_median"])
        pupils.append(d - b)
    env = {e: level("5_environment", "environment", "William", environment=e) for e in ("Indoor", "Outdoor")}
    pursuit = {}
    for r in rows(FACTORS / "6_pursuit/recordings.csv"):
        pursuit.setdefault(r["task"], []).append(float(r["residual_p_std_deg"]))
    static, moving = (statistics.median(pursuit[t]) for t in ("Static", "Pursuit"))
    for name, t in [("distance P1", test("William", "1_distance", "4 m − 1 m", acc)),
                    ("outdoor dispersion", test("William", "5_environment", "environment", pstd, 40)),
                    ("pursuit dispersion", test("William", "6_pursuit", "task", "residual_p_std_deg", 58))]:
        assert float(t["p_holm"]) < ALPHA, name
    rec = lambda folder, col="recording_name", name="fixations.csv": len(
        {r[col] for r in rows(FACTORS / folder / name)})

    stable = r"\textit{stable}"
    body = [
        (f"Viewing distance & {rec('1_distance')} & 1, 2, 4\\,m"
         f" & error $+${d1:.2f}\\dg{{}} / $+${d2:.2f}\\dg{{}} (1$\\to$4\\,m)$^*$; gaze shifts downward & {stable}"),
        (f"Vertical position & {rec('2_position')} & upper vs.\\ lower row"
         f" & lower row $+${lower_sig[-1][0]:.2f}\\dg{{}} / $+${lower_sig[0][0]:.2f}\\dg{{}} in two"
         f" participants$^*$, {stable} in the others"
         f" & precision consistently poorer in the lower row$^{{\\ddagger}}$"),
        f"Eccentricity & {rec('2_position')} & 0--30\\dg{{}} & {stable} & {stable}",
        (f"Bright / dark & {rec('4_illumination')} & pupil $+${min(pupils):.1f}--{max(pupils):.1f}\\,mm"
         f" & {stable} & {stable}"),
        (f"Indoor / outdoor & {rec('5_environment')} & pupil {float(env['Indoor']['pupil_mm_median']):.1f}"
         f"$\\to${float(env['Outdoor']['pupil_mm_median']):.1f}\\,mm & {stable}"
         f" & dispersion {float(env['Indoor']['p_std_deg_median']):.2f}$\\to$"
         f"{float(env['Outdoor']['p_std_deg_median']):.2f}\\dg{{}}$^*$"),
        (f"Smooth pursuit & {len(rows(FACTORS / '6_pursuit/recordings.csv'))} & static vs.\\ pursuit & {stable}"
         f" & dispersion {static:.2f}$\\to${moving:.2f}\\dg{{}}$^*$"),
        f"Repetition & {rec('8_drift')} & up to 8 within a day & {stable} (no drift) & {stable}",
        f"Recording day & {rec('7_session')} & 2--5 days & differed for one participant$^{{*,\\dagger}}$"
        f" & differed for one participant$^{{*,\\dagger}}$",
    ]
    lines = [r"% Generated by scripts/make_tables.py from gaze_accuracy/factors/controlled.",
             r"\begin{tabular}{@{}p{0.15\textwidth}@{\hskip 4pt}r@{\hskip 8pt}p{0.15\textwidth}"
             r"p{0.33\textwidth}p{0.24\textwidth}@{}}",
             r"\toprule",
             r"Factor & Rec. & Conditions & Accuracy and bias & Dispersion and precision \\",
             r"\midrule"]
    lines += [b + r" \\" for b in body]
    lines += [r"\bottomrule", r"\end{tabular}"]
    (OUT / "tab_controlled_factors.tex").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    OUT.mkdir(exist_ok=True)
    driving_table()
    controlled_table()
